"""Generate lightpanda/_methods.py from the binary's tools/list schemas.

Emits one concrete, annotated, documented method per browser tool, with the
tool name and its parameters in snake_case, all forwarding to ``Session.call``
(which maps them back to the schema's names). Each docstring carries the tool
description and a Google-style ``Args:`` section from the schema's property
descriptions, so IDEs and pdoc show what every argument means. Tools that
declare an ``outputSchema`` answer with ``structuredContent``, which
``Session.call`` returns as a ``PageResult``, so those methods are annotated
with it and get a ``Returns:`` section listing its attributes from the
schema's property descriptions; the rest stay ``Any``. Tools that take a
``backendNodeId`` also get a method on ``ElementMethods``, aimed at the element
it is called on. Being real code, the methods are
visible to IDEs, type checkers, and pdoc alike. Run with a binary available:

    uv run --no-project python scripts/generate_methods.py

CI regenerates and diffs the file to catch tool-schema drift.
"""

from __future__ import annotations

import keyword
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))

from lightpanda import Browser  # noqa: E402
from lightpanda.browser import (  # noqa: E402
    _ELEMENT_PARAMS,
    _ELEMENT_TOOLS,
    _SESSION_TOOLS,
    PageResult,
    _snake,
)

PY_TYPES = {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "object": "dict", "array": "list"}

# String params that carry JSON, which `Session.call` serializes from a dict or list.
JSON_STRING_PARAMS = {("extract", "schema"), ("classify", "questions")}

HEADER = '''\
"""Generated by scripts/generate_methods.py — do not edit.

One method per lightpanda browser tool, signatures derived from the tool
JSON schemas, with tool and parameter names in snake_case (the schemas'
camelCase names still work through ``Session.call``). ``ElementMethods``
holds the tools that take a ``backendNodeId``, aimed at the element itself.
The ``Async`` classes are the same surfaces with ``async def`` signatures.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:
    from .async_browser import AsyncElement
    from .browser import Element, PageResult
'''

CLASS_HEADER = '''\

class {cls}:
    {prefix}def call(self, tool: str, **kwargs: Any) -> Any:
        raise NotImplementedError
'''


def returns_section(name: str, output_schema: dict) -> str:
    """A Google-style ``Returns:`` section for a tool answering with
    ``structuredContent``: the ``PageResult`` attributes, described by the
    output schema's properties."""
    lines = ["Returns:", "    PageResult: The sentence above, with these attributes (None when absent):", ""]
    for prop, spec in output_schema.get("properties", {}).items():
        attr = _snake(prop)
        if attr not in PageResult.__annotations__:
            raise SystemExit(f"tool {name}: output property {prop!r} has no PageResult attribute")
        lines.append(f"    - `{attr}`: {spec.get('description', '').strip()}")
    return "\n".join(lines)


def docstring(description: str, args: list[tuple[str, str]], returns: str = "") -> str:
    """The method docstring: the tool description, then a Google-style
    ``Args:`` section built from the schema's property descriptions, then
    ``returns`` when given."""
    text = description.strip()
    documented = [(arg, desc.strip()) for arg, desc in args if desc.strip()]
    if documented:
        text += "\n\nArgs:\n" + "\n".join(f"    {arg}: {desc}" for arg, desc in documented)
    if returns:
        text += "\n\n" + returns
    body = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    lines = body.split("\n")
    if len(lines) == 1:
        return f'        """{body}"""'
    indented = "\n".join(f"        {line}" if line else "" for line in lines)
    return f'        """{indented.lstrip()}\n        """'


def method_source(name: str, spec: dict, is_async: bool = False, on_element: bool = False) -> str:
    schema = spec["schema"]
    properties = schema.get("properties", {})
    if on_element:
        properties = {prop: v for prop, v in properties.items() if prop not in _ELEMENT_PARAMS}
    required = set(schema.get("required", []))
    args = {prop: _snake(prop) for prop in properties}
    for prop, arg in args.items():
        if keyword.iskeyword(arg) or not arg.isidentifier():
            raise SystemExit(f"tool {name}: property {prop!r} is not a valid Python parameter")
    if len(set(args.values())) != len(args):
        raise SystemExit(f"tool {name}: properties collide once in snake_case: {sorted(args)}")

    params = ["self"]
    if properties:
        params.append("*")
    forwards = []
    documented = []
    for prop in sorted(properties, key=lambda p: p not in required):
        arg = args[prop]
        py_type = PY_TYPES.get(properties[prop].get("type", ""), "Any")
        if (name, prop) in JSON_STRING_PARAMS:
            py_type = "str | dict | list"
        if prop in required:
            params.append(f"{arg}: {py_type}")
        else:
            params.append(f"{arg}: {py_type} | None = None")
        forwards.append(f"{arg}={arg}")
        documented.append((arg, properties[prop].get("description", "")))

    snake = _snake(name)
    call_args = ", ".join([f'"{name}"'] + forwards)
    prefix = "async def" if is_async else "def"
    await_ = "await " if is_async else ""
    output_schema = spec.get("output_schema")
    returns = "PageResult" if output_schema else "Any"
    if name in _ELEMENT_TOOLS:
        returns = "list[AsyncElement]" if is_async else "list[Element]"
    lines = [f"    {prefix} {snake}({', '.join(params)}) -> {returns}:"]
    section = returns_section(name, output_schema) if output_schema else ""
    lines.append(docstring(spec["description"], documented, section))
    lines.append(f"        return {await_}self.call({call_args})")
    return "\n".join(lines)


def main() -> None:
    out = Path(__file__).parent.parent / "lightpanda" / "_methods.py"
    with Browser() as browser:
        tools = {k: v for k, v in browser.tools.items() if k not in _SESSION_TOOLS}

    on_node = sorted(name for name in tools if "backendNodeId" in tools[name]["schema"].get("properties", {}))
    # Elements are dicts: a tool must not shadow one of dict's methods.
    if shadowed := [name for name in on_node if hasattr(dict, _snake(name))]:
        raise SystemExit(f"tools {shadowed} would shadow dict methods on Element")
    blocks = [HEADER]
    for is_async in (False, True):
        prefix = "Async" if is_async else ""
        blocks.append(CLASS_HEADER.format(cls=f"{prefix}SessionMethods", prefix="async " if is_async else ""))
        blocks += [method_source(name, tools[name], is_async) for name in sorted(tools)]
        blocks.append(CLASS_HEADER.format(cls=f"{prefix}ElementMethods", prefix="async " if is_async else ""))
        blocks += [method_source(name, tools[name], is_async, on_element=True) for name in on_node]

    source = "\n".join(blocks) + "\n"
    compile(source, str(out), "exec")
    out.write_text(source)
    print(f"wrote {out} ({len(tools)} tools, {len(on_node)} on elements)")


if __name__ == "__main__":
    main()
